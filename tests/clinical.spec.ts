test('large images use an accessible in-page dialog without navigation',async({page,context})=>{
 await page.goto('/')
 await page.getByRole('button',{name:'02 干眼检查',exact:true}).click()
 const trigger=page.getByRole('button',{name:'放大图片：操作示意 · 试纸放在哪里',exact:true})
 const url=page.url(),tabs=context.pages().length
 await trigger.click()
 const modal=page.getByRole('dialog',{name:'大图：操作示意 · 试纸放在哪里',exact:true})
 await expect(modal).toBeVisible()
 await expect(modal.getByRole('img')).toBeVisible()
 expect(context.pages()).toHaveLength(tabs);expect(page.url()).toBe(url)
 await page.screenshot({path:'test-results/image-modal.png'})
 await page.keyboard.press('Escape');await expect(modal).not.toBeVisible();await expect(trigger).toBeFocused()
 await trigger.click();await modal.getByRole('button',{name:'关闭大图',exact:true}).click();await expect(modal).not.toBeVisible()
 await page.setViewportSize({width:390,height:844});await trigger.click()
 await expect(modal).toBeVisible()
 const box=(await modal.boundingBox())!;expect(box.width).toBeLessThanOrEqual(390)
 await page.screenshot({path:'test-results/image-modal-mobile.png'})
 await page.mouse.click(1,1);await expect(modal).not.toBeVisible()
 await page.getByText('资料与图片版权信息',{exact:true}).click()
 await expect(page.locator('.reference-content')).toBeVisible()
})

