test('mesh picking, camera rotation and labels',async({page})=>{
 await page.goto('/');await expect(page.locator('.model-label')).toHaveCount(6)
 await page.getByLabel('结构标签',{exact:true}).uncheck()
 await expect(page.locator('.model-label')).toHaveCount(0)
 const canvas=page.locator('canvas');const rect=(await canvas.boundingBox())!
 // Click the exposed central tear-film cap, then verify the actual mesh event.
 await canvas.click({position:{x:rect.width*.5,y:rect.height*.5}})
 await expect(page.getByRole('complementary',{name:'结构说明'})).toContainText('维持湿润')
 const before=await canvas.screenshot()
 await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5)
 await page.mouse.down();await page.mouse.move(rect.x+rect.width*.5+95,rect.y+rect.height*.5+30,{steps:10});await page.mouse.up()
 const after=await canvas.screenshot();expect(before.equals(after)).toBe(false)
 await page.getByRole('button',{name:'侧面',exact:true}).click()
 await expect(page.getByRole('button',{name:'侧面',exact:true})).toHaveAttribute('aria-pressed','true')
})
