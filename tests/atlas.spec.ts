import {test,expect} from '@playwright/test'
test('structure selection, visibility, view switching and reset',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await expect(page.locator('canvas')).toBeVisible()
 await page.getByRole('button',{name:'03 泪腺 Lacrimal gland'}).click()
 await expect(page.getByRole('complementary',{name:'结构说明'})).toContainText('提供水分')
 await page.getByRole('button',{name:'隐藏泪腺',exact:true}).click()
 await expect(page.getByRole('button',{name:'显示泪腺',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'仅显示所选结构'}).click()
 await expect(page.locator('.visibility[aria-pressed="true"]')).toHaveCount(1)
 await page.getByRole('button',{name:/02 睑板腺放大/}).click()
 await expect(page.getByRole('complementary',{name:'结构说明'})).toContainText('提供油脂')
 await page.getByRole('button',{name:'重置视图'}).click()
 await expect(page.locator('.visibility[aria-pressed="true"]')).toHaveCount(6)
 await expect(page.getByRole('heading',{name:'3D 视图暂时无法显示'})).toHaveCount(0)
 expect(errors).toEqual([])
})
test('tear film controls and reduced motion',async({page})=>{
 await page.emulateMedia({reducedMotion:'reduce'});await page.goto('/')
 await page.getByRole('button',{name:/03 泪膜与眨眼/}).click()
 await expect(page.getByRole('button',{name:'播放演示'})).toBeDisabled()
 await page.getByRole('slider').fill('80')
 await expect(page.locator('output')).toHaveText('80%')
 await page.getByLabel('不完整眨眼情境').check()
 await page.getByRole('button',{name:'模拟一次眨眼'}).click()
 await expect(page.locator('output')).toHaveText('35%')
 await page.getByLabel('不完整眨眼情境').uncheck()
 await page.getByRole('button',{name:'模拟一次眨眼'}).click()
 await expect(page.locator('output')).toHaveText('0%')
})
