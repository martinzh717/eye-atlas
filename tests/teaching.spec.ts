import {test,expect} from '@playwright/test'
test('eight exams each provide three labeled simulations and selectable explanations',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/');await page.getByRole('button',{name:'02 干眼检查',exact:true}).click()
 const guide=page.getByRole('region',{name:'干眼检查指南'})
 for(let i=0;i<8;i++){
  await guide.locator('.clinical-menu button').nth(i).click()
  const teaching=page.getByRole('region',{name:'单项教学案例对照'})
  await expect(teaching).toContainText('模拟教学案例')
  await expect(teaching.locator('.teaching-card')).toHaveCount(3)
  await expect(teaching.locator('.teaching-card').first()).toHaveAttribute('aria-pressed','true')
  await teaching.locator('.teaching-card').last().click()
  await expect(teaching.locator('.teaching-card').last()).toHaveAttribute('aria-pressed','true')
  await expect(teaching.locator('.teaching-difference')).not.toBeEmpty()
 }
 await guide.locator('.clinical-menu button').nth(1).click()
 const teaching=page.getByRole('region',{name:'单项教学案例对照'})
 await teaching.locator('.teaching-card').nth(1).click()
 await expect(teaching).toContainText('10 秒处在正常参考范围的下限')
 await expect(teaching.locator('.teaching-difference')).toContainText('等于 10')
 await guide.locator('.clinical-menu button').nth(3).click()
 await page.locator('.teaching-card').nth(1).click()
 await expect(page.locator('.teaching-cases .teaching-difference')).toContainText('等于”也纳入阈值')
 await expect(guide.locator('.exam-case')).toContainText('真实案例 A')
 expect(errors).toEqual([])
 await page.locator('.teaching-cases').screenshot({path:'test-results/teaching-cases.png'})
})
test('combined cases distinguish supply and stability and work on mobile',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'02 干眼检查',exact:true}).click()
 await page.locator('.combined-cases summary').click()
 const panel=page.getByRole('region',{name:'综合教学案例'})
 await expect(panel.locator('.combined-tabs button')).toHaveCount(4)
 await panel.getByRole('button',{name:'03 分泌正常，泪膜不稳',exact:true}).click()
 await expect(panel.getByRole('row').filter({hasText:'Schirmer'})).toContainText('18 mm / 5 min')
 await expect(panel.getByRole('row').filter({hasText:'首次 NIBUT'})).toContainText('4 秒')
 await expect(panel.locator('.teaching-difference')).toContainText('水量和稳定性可以不一致')
 await panel.getByRole('button',{name:'04 水量与覆盖都有异常',exact:true}).click()
 await expect(panel.getByRole('row').filter({hasText:'Schirmer'})).toContainText('3 mm / 5 min')
 await expect(panel).toContainText('牙膏样 · 3 分')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await panel.getByRole('button',{name:'01 各项表现正常',exact:true}).click()
 await expect(panel).toContainText('15 秒')
 await page.screenshot({path:'test-results/teaching-mobile.png',fullPage:true})
})
